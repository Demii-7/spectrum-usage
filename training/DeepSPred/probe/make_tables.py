"""Build results/TABLES.md from the probe JSON files in results/ (no hand transcription).

  python training/DeepSPred/probe/make_tables.py
"""
from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).resolve().parent / "results"


def load(name: str) -> dict:
    return json.loads((R / name).read_text())


def f(x, nd=1):
    return "-" if x is None else f"{x:.{nd}f}"


def render_table(d: dict) -> str:
    out = []
    for ds, v in d["datasets"].items():
        out.append(f"\n**{ds}** ({v['n_files']} files, {v['n_test']} test frames)\n")
        out.append("| variant | persistence k=1 | k=8 | k=20 | lookback-mean k=1 | k=8 | k=20 | global-SSIM(k=18) of persistence |")
        out.append("|---|---|---|---|---|---|---|---|")
        for n, r in v["variants"].items():
            p, l = r["persistence_mse"], r["lookback_mean_mse"]
            out.append(f"| {n} | {f(p[0])} | {f(p[7])} | {f(p[19])} | {f(l[0])} | {f(l[7])} | {f(l[19])} | {r['persistence_global_ssim_k18']} |")
    return "\n".join(out)


def acf_table(d: dict) -> str:
    out = []
    for ds, v in d["datasets"].items():
        out.append(f"\n**{ds}** (fit {v['n_fit']} frames, test {v['n_test']} frames)\n")
        out.append("| variant | mean-image MSE | ceiling k=1 | k=8 | k=20 | rise k=1→20 | skill k=1 | skill k=8 | rho(1) | rho(8) |")
        out.append("|---|---|---|---|---|---|---|---|---|---|")
        for n, r in sorted(v["variants"].items()):
            q, s, p = r["ridge_mse"], r["skill"], r["rho"]
            out.append(f"| {n} | {f(r['clim_mse'])} | {f(q[0])} | {f(q[7])} | {f(q[19])} | {100 * (q[19] / q[0] - 1):.1f}% | "
                       f"{s[0]:.3f} | {s[7]:.3f} | {p[0]:.3f} | {p[7]:.3f} |")
    return "\n".join(out)


def range_table(d: dict) -> str:
    out = []
    for ds, v in d["datasets"].items():
        out.append(f"\n**{ds}** ({v['n_files']} files)\n")
        out.append("| window | full lo..hi (dB) | full span | sampled (every 50th) span | train-only span | 0.1-99.9 pct span | per-frame median span |")
        out.append("|---|---|---|---|---|---|---|")
        for w, r in v["windows"].items():
            fl = r["full"]
            out.append(f"| {w} | {fl['lo']:.1f}..{fl['hi']:.1f} | {fl['span']:.1f} | {r['sampled']['span']:.1f} | {r['train']['span']:.1f} | "
                       f"{r['pct_0.1_99.9_mean_of_frames']['span']:.1f} | {r['frame_span_median']:.1f} |")
    return "\n".join(out)


def main():
    parts = ["# Probe result tables (generated by make_tables.py from the JSON files in this directory)\n",
             "All MSE in uint8 pixel units, mean over pixels and channels (the paper's `uint8_mean_per_channel` space, MAX_I = 255).\n"]
    parts.append("\n## 1. Rendering probe: trivial predictors (rendering_probe_20261110T172330.json)\n")
    parts.append(render_table(load("rendering_probe_20261110T172330.json")))
    parts.append("\n\n## 2. Temporal structure and linear ceiling, 18 renderings (acf_probe_20261110T172942.json)\n")
    parts.append(acf_table(load("acf_probe_20261110T172942.json")))
    parts.append("\n\n## 3. Window study: Tukey, hop, detrend; first run (acf_probe_tukey_20261110T180408.json)\n")
    parts.append(acf_table(load("acf_probe_tukey_20261110T180408.json")))
    parts.append("\n\n## 4. Window study: second run, adds exact scipy defaults tukey224d (acf_probe_tukey_20261110T183333.json)\n")
    parts.append(acf_table(load("acf_probe_tukey_20261110T183333.json")))
    parts.append("\n\n## 5. Rectangular window, hop 126, with and without detrend (acf_probe_rect_20261110T183943.json)\n")
    parts.append(acf_table(load("acf_probe_rect_20261110T183943.json")))
    parts.append("\n\n## 6. dB range by window and by which frames set it (range_probe_20261110T184251.json)\n")
    parts.append(range_table(load("range_probe_20261110T184251.json")))
    parts.append("\n\n## 7. Ceiling under full-dataset and train-only dB range (acf_probe_range_20261110T185554.json)\n")
    rng = load("acf_probe_range_20261110T185554.json")
    parts.append(acf_table(rng))
    parts.append("\n\nRanges used (lo..hi dB) per window:\n")
    for ds, v in rng["datasets"].items():
        if v.get("range"):
            parts.append(f"- **{ds}**: " + "; ".join(f"{w} {lo:.1f}..{hi:.1f}" for w, (lo, hi) in v["range"].items()))
    (R / "TABLES.md").write_text("\n".join(parts) + "\n")
    print("wrote", R / "TABLES.md")


if __name__ == "__main__":
    main()
