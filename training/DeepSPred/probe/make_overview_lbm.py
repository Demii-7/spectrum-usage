"""Build results/OVERVIEW_LBM.md: lookback-mean MSE (the headline metric) and the linear ceiling, per rendering, vs the paper.

  python training/DeepSPred/probe/make_overview_lbm.py

Lookback mean = predict frame t+k as the mean of the last 20 input frames (no fitting). It is NOT a bound: unlike the ceiling it adapts to slow drift.
All rows use the FULL dB range; cross-validation is shown with its own range and with FM's range.
"""
from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).resolve().parent / "results"
N = "acf_probe_overview_20261110T200458.json"
d = json.loads((R / N).read_text())["datasets"]
fm, cv, cf = d["fm_full"]["variants"], d["crossval_full"]["variants"], d["crossval_fmfull"]["variants"]
P_FM, P_CV = 448.76, 531.43


def lab(n: str) -> str:
    t = n.split("_")
    names = {"hann126": "Hann, hop 126", "hamm128": "Hamming, hop 128", "rect126": "Rectangular, hop 126", "tukey126": "Tukey .25, hop 126",
             "tukey126d": "Tukey .25, hop 126, detrend", "tukey224": "Tukey .25, hop 224", "tukey224d": "scipy defaults (Tukey .25, hop 224, detrend)",
             "rect127c": "torch-style (rect, hop 127, reflect pad)"}
    s = names.get(t[0], t[0])
    for tok in t[1:]:
        if tok.startswith("crop"):
            s += {"A": ", crop A (90-110 MHz)", "C": ", crop C (+-10 MHz of 99)"}[tok[4:]]
        elif tok.startswith("eps"):
            s += f", dB floor 1e-{tok[3:]}"
        elif tok.startswith("jpeg"):
            s += f", JPEG q{tok[4:]}"
        elif tok.startswith("blur"):
            s += f", blur sigma {tok[4:]}"
    return s


def group(n: str) -> str:
    if "jpeg" in n or "blur" in n:
        return "C. smoothing / codec"
    if "crop" in n:
        return "E. band crop"
    if "rect127c" in n:
        return "D. torch.stft-style (dB floor only changes cross-val)"
    return "A. window / hop / detrend (raw)"


rows: dict = {}
for n in fm:
    rows.setdefault(group(n), []).append(n)
out = ["# Lookback-mean MSE (headline) and linear ceiling, full dB range, k=8\n",
       "Generated by `make_overview_lbm.py` from `acf_probe_overview_20261110T200458.json`. **Lookback mean** = mean of the last 20 input frames (no fitting; not a bound, it adapts to drift). "
       "**Ceiling** = best linear predictor from 5 frames fitted on the validation block (fixed mean image from that block). MSE in uint8 units. "
       "Paper (trained model): FM 448.76 at k=8 [T], cross-validation 531.43 at k=12 [T], rises +3.6% / +2.3% [P]. 'rise' = k=20 over k=1 for the lookback mean. "
       "'CV own' = cross-validation normalised with its own range; 'CV FM-rng' = with FM's range (what an FM-trained model would see).\n",
       "| option | FM lookback-mean | FM ceiling | CV own lookback-mean | CV own ceiling | CV FM-rng lookback-mean | CV own / FM | CV FM-rng / FM | FM rise | CV rise | FM vs paper |",
       "|---|---|---|---|---|---|---|---|---|---|---|",
       f"| **PAPER (trained 3D-SwinSTB)** | {P_FM} [T] | - | {P_CV} [T] | - | - | 1.18 | - | +3.6% [P] | +2.3% [P] | 1.00x |"]
for g in sorted(rows):
    out.append(f"| *{g}* | | | | | | | | | | |")
    for n in sorted(rows[g], key=lambda x: fm[x]["lbm_mse"][7]):
        a, b, c = fm[n], cv[n], cf[n]
        l = lambda v: v["lbm_mse"][7]
        rise = lambda v: 100 * (v["lbm_mse"][19] / v["lbm_mse"][0] - 1)
        out.append(f"| {lab(n)} | {l(a):.0f} | {a['ridge_mse'][7]:.0f} | {l(b):.0f} | {b['ridge_mse'][7]:.0f} | {l(c):.0f} | {l(b) / l(a):.2f} | {l(c) / l(a):.2f} | "
                   f"{rise(a):+.1f}% | {rise(b):+.1f}% | {l(a) / P_FM:.2f}x |")
(R / "OVERVIEW_LBM.md").write_text("\n".join(out) + "\n")
print("wrote", R / "OVERVIEW_LBM.md")
